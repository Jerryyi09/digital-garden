export function hasBookReadalong(name) {
  if (!name) return false
  if (READALONG_BOOKS.has(name)) return true
  const norm = name.trim().toLowerCase()
  for (const b of READALONG_BOOKS) {
    if (b.toLowerCase() === norm) return true
  }
  return false
}

