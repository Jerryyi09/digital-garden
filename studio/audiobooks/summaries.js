export function getBookSummary(name) {
  if (!name) return ""
  if (BOOK_SUMMARIES[name]) return BOOK_SUMMARIES[name]
  const normalized = name.trim().toLowerCase()
  for (const [key, val] of Object.entries(BOOK_SUMMARIES)) {
    if (key.toLowerCase() === normalized) return val
  }
  return ""
}

