export function getJacketColors(name) {
  let hash = 0
  const str = String(name || "Book")
  for (let i = 0; i < str.length; i++) {
    hash = (hash << 5) - hash + str.charCodeAt(i)
    hash |= 0
  }
  const idx = Math.abs(hash) % JACKET_PALETTES.length
  return JACKET_PALETTES[idx]
}
